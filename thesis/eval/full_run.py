"""The full matrix run (E9-09, SCRUM-110).

Runs the complete frozen matrix — every evaluation bundle × every condition × k repetitions
(METHODS.md §2, C-03) — on the pinned hosted model (ADR-0001), persists one result row per item,
verifies the row count and the model revision, hashes the results and records the spend. This is the
run that produces every number the thesis reports.

    LLM_BASE_URL=... LLM_MODEL=... caffeinate -is uv run python -m thesis.eval.full_run

Crash-safe and resumable: each finished item's row is appended to a JSONL and the item is marked
in a ledger, so an interruption re-runs only unfinished items (`--resume`). A fresh run (the
default) resets the ledger, the row file and the call-log offset. The run is long (~29k calls); the
cap must be active first (DoR), and the provider dashboard is the authoritative spend.
"""

from __future__ import annotations

import hashlib
import json
import os
import sys
from dataclasses import asdict
from pathlib import Path
from typing import cast

from thesis.assemble.bundles import bundle_set_hash
from thesis.config import config_hash
from thesis.eval.cost import USD_PER_EUR, row_eur
from thesis.eval.exploratory import _call_totals_by_item, _line_count, _provenance

REPO_ROOT = Path(__file__).resolve().parents[2]
RESULTS_DIR = REPO_ROOT / "results"
RESULTS_PARQUET = RESULTS_DIR / "results.parquet"
ROWS_JSONL = RESULTS_DIR / "full_run_rows.jsonl"
STATE_PATH = REPO_ROOT / "data" / "full_run" / "state.json"
LEDGER_PATH = REPO_ROOT / "data" / "full_run" / "ledger.jsonl"
FULL_RUN_MD = REPO_ROOT / "docs" / "eval" / "full_run.md"

# ADR-0001 upstream commit. DeepInfra does not certify the served commit, so this is the claimed
# revision recorded on every row (ADR-0001 "what the pin covers"); the revision check confirms the
# whole run used one model and one revision, catching a provider-side swap mid-run (the gotcha).
MODEL_REVISION = "0e9e39f249a16976918f6564b8830bc894c89659"


def _arg_int(args: list[str], flag: str) -> int | None:
    """Read `--flag N` from argv, or None if absent."""
    if flag in args:
        idx = args.index(flag)
        if idx + 1 < len(args):
            return int(args[idx + 1])
    return None


def verify_row_count(
    rows: list[dict[str, object]], n_bundles: int, n_conditions: int, k: int
) -> list[str]:
    """Return problems: the row count and the unique-item count must both equal bundles×conds×k."""
    expected = n_bundles * n_conditions * k
    problems: list[str] = []
    if len(rows) != expected:
        problems.append(
            f"row count {len(rows)} != expected {expected} (={n_bundles}×{n_conditions}×{k})"
        )
    keys = {(r["bundle_id"], r["config_hash"], r["repetition"]) for r in rows}
    if len(keys) != expected:
        problems.append(f"unique (bundle, condition, repetition) count {len(keys)} != {expected}")
    return problems


def verify_single_revision(rows: list[dict[str, object]], model: str, revision: str) -> list[str]:
    """Every LLM-bearing row (not Baseline A) must carry the one pinned model and revision."""
    problems: list[str] = []
    models = {
        (str(r["model"]), str(r["model_revision"]))
        for r in rows
        if str(r["strategy"]) != "ml_classifier"
    }
    if models != {(model, revision)} and models:
        problems.append(f"LLM calls used more than the pinned model/revision: {sorted(models)}")
    return problems


def compute_spend(rows: list[dict[str, object]]) -> dict[str, float]:
    """Total tokens, USD and EUR over all rows (rejected calls included, per E0-11)."""
    tokens_in = sum(int(cast("int", r["tokens_in"])) for r in rows)
    tokens_out = sum(int(cast("int", r["tokens_out"])) for r in rows)
    eur = sum(
        row_eur(int(cast("int", r["tokens_in"])), int(cast("int", r["tokens_out"]))) for r in rows
    )
    usd = eur * USD_PER_EUR  # row_eur returns EUR; recover USD for the record
    return {
        "tokens_in": float(tokens_in),
        "tokens_out": float(tokens_out),
        "usd": round(usd, 4),
        "eur": round(usd / USD_PER_EUR, 4),
    }


def hash_file(path: Path) -> str:
    """SHA-256 of a file's bytes."""
    return hashlib.sha256(path.read_bytes()).hexdigest()


def write_full_run_md(
    *,
    n_rows: int,
    n_bundles: int,
    n_conditions: int,
    k: int,
    eval_hash: str,
    results_hash: str,
    spend: dict[str, float],
    model: str,
    revision: str,
    problems: list[str],
    path: Path = FULL_RUN_MD,
) -> None:
    status = "OK" if not problems else "PROBLEMS — see below"
    path.parent.mkdir(parents=True, exist_ok=True)
    body = [
        "# Full matrix run (E9-09, SCRUM-110)",
        "",
        "GENERATED by `python -m thesis.eval.full_run`. This run produces the thesis results.",
        "",
        f"- Rows: **{n_rows}**  (expected {n_bundles} bundles × {n_conditions} conditions × k={k})",
        f"- Evaluation set hash: `{eval_hash}`",
        f"- Results file hash (SHA-256 of `results/results.parquet`): `{results_hash}`",
        f"- Model: `{model}`  revision `{revision}`",
        "  (ADR-0001; the provider does not certify the served commit)",
        f"- Verification: **{status}**",
        *(f"  - {p}" for p in problems),
        "",
        "## Spend (from the call log; the provider dashboard is authoritative)",
        "",
        "| Input tokens | Output tokens | USD | EUR |",
        "|---|---|---|---|",
        f"| {int(spend['tokens_in'])} | {int(spend['tokens_out'])} | "
        f"{spend['usd']} | {spend['eur']} |",
        "",
        "Prices: dated ADR-0001 figures (DeepInfra 2026-10-04). Record the results-file hash in",
        "`docs/thesis_notes.md`.",
        "",
    ]
    path.write_text("\n".join(body) + "\n", encoding="utf-8")


def main(argv: list[str] | None = None) -> int:  # pragma: no cover - the live run is Roy's
    args = sys.argv[1:] if argv is None else argv
    if not os.environ.get("LLM_BASE_URL"):
        print("set LLM_BASE_URL/LLM_MODEL/LLM_API_KEY for the hosted model first", file=sys.stderr)
        return 2
    os.environ.setdefault("TOKENIZERS_PARALLELISM", "false")
    os.environ.setdefault("OMP_NUM_THREADS", "1")
    resume = "--resume" in args

    from thesis.assemble.build_frozen import build
    from thesis.eval.ledger import Ledger
    from thesis.eval.results import ResultRow, build_row
    from thesis.eval.run import CONCURRENCY, K, RunResult, load_conditions, run_matrix
    from thesis.kb.retrieve import retrieve
    from thesis.llm.client import LLMClient
    from thesis.obs.logging import LOG_PATH

    client = LLMClient.from_env(model_revision=MODEL_REVISION)
    conditions = load_conditions(_provenance(client))
    eval_bundles = build().eval_bundles
    limit = _arg_int(args, "--limit")  # a small smoke run that exercises the whole path cheaply
    if limit is not None:
        eval_bundles = sorted(eval_bundles, key=lambda b: b.bundle_id)[:limit]
    eval_hash = bundle_set_hash(eval_bundles)
    bundles_by_id = {b.bundle_id: b for b in eval_bundles}
    configs_by_hash = {config_hash(c): c for c in conditions}

    RESULTS_DIR.mkdir(parents=True, exist_ok=True)
    LEDGER_PATH.parent.mkdir(parents=True, exist_ok=True)
    if resume and STATE_PATH.exists():
        since_line = int(json.loads(STATE_PATH.read_text())["since_line"])
    else:
        ROWS_JSONL.unlink(missing_ok=True)
        LEDGER_PATH.unlink(missing_ok=True)
        since_line = _line_count(LOG_PATH)
        STATE_PATH.write_text(json.dumps({"since_line": since_line}), encoding="utf-8")

    retrieve("warmup")

    def sink(result: RunResult) -> None:
        row = build_row(
            result,
            bundles_by_id[result.bundle_id],
            configs_by_hash[result.config_hash],
            tokens_in=0,
            tokens_out=0,
            latency_ms=0.0,
        )
        with ROWS_JSONL.open("a", encoding="utf-8") as handle:
            handle.write(json.dumps(asdict(row)) + "\n")

    ledger = Ledger(LEDGER_PATH)
    run_matrix(
        eval_bundles,
        conditions,
        client=client,
        ledger=ledger,
        sink=sink,
        k=K,
        max_workers=int(os.environ.get("FULL_RUN_MAX_WORKERS", str(CONCURRENCY))),
    )

    rows = _finalize(LOG_PATH, since_line, set(configs_by_hash), set(bundles_by_id))
    _write_parquet(rows)
    problems = verify_row_count(rows, len(eval_bundles), len(conditions), K)
    problems += verify_single_revision(rows, client.model, MODEL_REVISION)
    spend = compute_spend(rows)
    results_hash = hash_file(RESULTS_PARQUET)
    write_full_run_md(
        n_rows=len(rows),
        n_bundles=len(eval_bundles),
        n_conditions=len(conditions),
        k=K,
        eval_hash=eval_hash,
        results_hash=results_hash,
        spend=spend,
        model=client.model,
        revision=MODEL_REVISION,
        problems=problems,
    )
    _ = ResultRow  # keep the import meaningful for the schema reference
    print(f"full run complete: {len(rows)} rows; spend USD {spend['usd']}; hash {results_hash}")
    for p in problems:
        print(f"PROBLEM: {p}", file=sys.stderr)
    return 0 if not problems else 1


def _finalize(  # pragma: no cover - reads the live run's call log
    log_path: Path, since_line: int, config_hashes: set[str], bundle_ids: set[str]
) -> list[dict[str, object]]:
    rows = [
        json.loads(line)
        for line in ROWS_JSONL.read_text(encoding="utf-8").splitlines()
        if line.strip()
    ]
    totals = _call_totals_by_item(log_path, config_hashes, bundle_ids, since_line=since_line)
    for row in rows:
        key = (str(row["bundle_id"]), str(row["config_hash"]), int(row["repetition"]))
        t_in, t_out, latency = totals.get(key, (0, 0, 0.0))
        row["tokens_in"], row["tokens_out"], row["latency_ms"] = t_in, t_out, latency
    return rows


def _write_parquet(rows: list[dict[str, object]]) -> None:  # pragma: no cover
    import pyarrow as pa  # type: ignore[import-untyped]
    import pyarrow.parquet as pq  # type: ignore[import-untyped]

    pq.write_table(pa.Table.from_pylist(rows), RESULTS_PARQUET)


if __name__ == "__main__":  # pragma: no cover
    raise SystemExit(main())


__all__ = [
    "compute_spend",
    "hash_file",
    "verify_row_count",
    "verify_single_revision",
    "write_full_run_md",
]
